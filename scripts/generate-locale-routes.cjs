/* Generate thin Spanish route adapters; English implementations are the source of truth. */
const fs = require('fs');
const path = require('path');
const ts = require('typescript');
const root = path.resolve(__dirname, '..');
const app = path.join(root, 'src/app');
const english = path.join(app, '(english)');
const spanish = path.join(app, '(spanish)/es');
const slash = value => value.split(path.sep).join('/');
const sourcePath = file => '@/app/(english)/' + slash(path.relative(english, file)).replace(/\.tsx?$/, '');
function walk(directory) {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap(entry =>
    entry.isDirectory() ? walk(path.join(directory, entry.name)) : [path.join(directory, entry.name)]);
}
function exportsOf(file) {
  const source = ts.createSourceFile(file, fs.readFileSync(file, 'utf8'), ts.ScriptTarget.Latest, true);
  const exports = new Set();
  for (const node of source.statements) {
    if (ts.isExportDeclaration(node) && node.exportClause && ts.isNamedExports(node.exportClause)) {
      for (const item of node.exportClause.elements) exports.add(item.name.text);
    }
    if (node.modifiers?.some(modifier => modifier.kind === ts.SyntaxKind.ExportKeyword)) {
      if (node.name) exports.add(node.name.text);
      if (ts.isVariableStatement(node)) {
        for (const declaration of node.declarationList.declarations) if (ts.isIdentifier(declaration.name)) exports.add(declaration.name.text);
      }
    }
  }
  return exports;
}
function write(file, text) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== text) fs.writeFileSync(file, text);
}
const files = walk(english).filter(file => /(?:page|layout|loading|error|not-found)\.tsx$/.test(file)).sort();
const imports = [`import type { Metadata } from 'next';`, `import { baseMetadata } from '@/lib/seo';`];
const entries = [];
for (const file of files) {
  const relative = path.relative(english, file);
  const name = path.basename(file);
  if (relative === 'layout.tsx') continue;
  const source = sourcePath(file);
  const exported = exportsOf(file);
  const route = '/' + slash(path.dirname(relative) === '.' ? '' : path.dirname(relative));
  let wrapper = `${name === 'error.tsx' ? "'use client';\n\n" : ''}// Generated by scripts/generate-locale-routes.cjs; edit the English implementation.\nexport { default } from '${source}';\n`;
  if (name === 'page.tsx') {
    const index = entries.length;
    let metadataFile = exported.has('metadata') || exported.has('generateMetadata') ? file : null;
    let directory = path.dirname(file);
    while (!metadataFile && directory !== english) {
      const layout = path.join(directory, 'layout.tsx');
      if (fs.existsSync(layout)) {
        const names = exportsOf(layout);
        if (names.has('metadata') || names.has('generateMetadata')) metadataFile = layout;
      }
      directory = path.dirname(directory);
    }
    let metadata = '() => baseMetadata';
    if (metadataFile) {
      const dynamicMetadata = exportsOf(metadataFile).has('generateMetadata');
      imports.push(`import { ${dynamicMetadata ? 'generateMetadata' : 'metadata'} as metadata${index} } from '${sourcePath(metadataFile)}';`);
      const metadataParams = [...path.relative(english, metadataFile).matchAll(/\[([a-zA-Z]\w*)\]/g)]
        .map(match => `${match[1]}: params[${JSON.stringify(match[1])}]`).join(', ');
      metadata = dynamicMetadata ? `({ params }) => metadata${index}({ params: { ${metadataParams} } })` : `() => metadata${index}`;
    }
    let params = 'undefined';
    if (exported.has('generateStaticParams')) {
      imports.push(`import { generateStaticParams as params${index} } from '${source}';`);
      params = `params${index}`;
      wrapper += `export { generateStaticParams } from '${source}';\n`;
    }
    entries.push(`  { pattern: ${JSON.stringify(route)}, metadata: ${metadata}, params: ${params} },`);
    wrapper += `import { metadataForRoute } from '@/i18n/route-metadata';\n\nexport async function generateMetadata({ params }: { params: Record<string, string> }) {\n  return metadataForRoute(${JSON.stringify(route)}, params, 'es');\n}\n`;
  }
  write(path.join(spanish, relative), wrapper);
}
write(path.join(root, 'src/i18n/route-sources.generated.ts'), `// Generated by scripts/generate-locale-routes.cjs.\n${imports.join('\n')}\n\ntype MetadataResolver = (props: { params: Record<string, string> }) => Metadata | Promise<Metadata>;\nexport interface RouteSource {\n  pattern: string;\n  metadata: MetadataResolver;\n  params?: () => Promise<Record<string, string>[]> | Record<string, string>[];\n}\nexport const routeSources: RouteSource[] = [\n${entries.join('\n')}\n];\n`);
console.log(`Generated ${entries.length} Spanish route patterns and their source registry.`);
